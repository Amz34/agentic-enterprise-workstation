#!/usr/bin/env python3
"""
Dual-Model Consensus Reviewer & AST / Security Auditor.
Validates git diffs generated by coder agents before merge.
"""

import re
import ast
from pathlib import Path
from typing import Dict, List, Any


class ReviewAuditor:
    SECRET_PATTERNS = [
        (r"(?i)aws_secret_access_key\s*=\s*['\"][A-Za-z0-9/\+=]{20,}['\"]", "AWS Secret Key"),
        (r"(?i)(api[_-]?key|auth[_-]?token|bearer)\s*=\s*['\"][A-Za-z0-9_\-\.]{16,}['\"]", "API/Auth Token"),
        (r"-----BEGIN (RSA|OPENSSH|EC|DSA)? PRIVATE KEY-----", "Private Key Header"),
        (r"(?i)password\s*=\s*['\"][^'\"]{6,}['\"]", "Hardcoded Plaintext Password"),
    ]

    def audit_file_content(self, file_path: str, content: str) -> Dict[str, Any]:
        """Perform static analysis, syntax verification, and secret scans on modified content."""
        findings: List[Dict[str, Any]] = []
        is_clean = True

        # 1. Secret Scanning
        for pattern, label in self.SECRET_PATTERNS:
            matches = re.findall(pattern, content)
            if matches:
                findings.append({
                    "severity": "CRITICAL",
                    "type": "SECRET_LEAK",
                    "file": file_path,
                    "message": f"Found probable hardcoded {label}",
                })
                is_clean = False

        # 2. Syntax Validation (Python AST)
        if file_path.endswith(".py"):
            try:
                ast.parse(content, filename=file_path)
            except SyntaxError as e:
                findings.append({
                    "severity": "BLOCKING",
                    "type": "SYNTAX_ERROR",
                    "file": file_path,
                    "message": f"Syntax error at line {e.lineno}: {e.msg}",
                })
                is_clean = False

        return {
            "file": file_path,
            "passed": is_clean,
            "findings": findings,
        }

    def audit_worktree(self, worktree_path: Path) -> Dict[str, Any]:
        """Audit all source files within a worktree."""
        all_results = []
        overall_passed = True

        for p in worktree_path.rglob("*.py"):
            if ".worktrees" in str(p) or ".git" in str(p):
                continue
            try:
                content = p.read_text(encoding="utf-8")
                res = self.audit_file_content(str(p.relative_to(worktree_path)), content)
                if not res["passed"]:
                    overall_passed = False
                all_results.append(res)
            except Exception as e:
                all_results.append({
                    "file": str(p),
                    "passed": False,
                    "findings": [{"severity": "ERROR", "message": str(e)}],
                })
                overall_passed = False

        return {
            "passed": overall_passed,
            "audited_count": len(all_results),
            "results": all_results,
        }
